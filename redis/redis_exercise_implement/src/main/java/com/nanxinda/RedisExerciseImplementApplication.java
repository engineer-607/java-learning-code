//NOTE
// /*
// * Redis 缓存更新策略对比
// *
// * +----------------+--------------------------------------------+--------------------------------------------+--------------------------------------------+
// * |                | 内存淘汰                                   | 超时剔除                                   | 主动更新                                   |
// * +----------------+--------------------------------------------+--------------------------------------------+--------------------------------------------+
// * | 说明           | 不用自己维护，利用 Redis 的内存淘汰机制。   | 给缓存数据添加 TTL 时间，到期后自动删除。   | 编写业务逻辑，在修改数据库的同时更新缓存。 |
// * |                | 当内存不足时自动淘汰部分数据。             | 下次查询时再更新缓存。                     |                                            |
// * |                | 下次查询时再更新缓存。                     |                                            |                                            |
// * +----------------+--------------------------------------------+--------------------------------------------+--------------------------------------------+
// * | 一致性         | 差                                         | 一般                                       | 好                                         |
// * +----------------+--------------------------------------------+--------------------------------------------+--------------------------------------------+
// * | 维护成本       | 无                                         | 低                                         | 高                                         |
// * +----------------+--------------------------------------------+--------------------------------------------+--------------------------------------------+
// *
// * 业务场景：
// *
// * +----------------+--------------------------------------------+
// * | 低一致性需求   | 使用内存淘汰机制                           |
// * |                | 例如：店铺类型的查询缓存                   |
// * +----------------+--------------------------------------------+
// * | 高一致性需求   | 使用主动更新，并以超时剔除作为兜底方案     |
// * |                | 例如：店铺详情查询的缓存                   |
// * +----------------+--------------------------------------------+
// */

//NOTE
// Redis 主动更新策略
// *
// * +------+----------------------------+------------------------------------------------------------+
// * | 序号 | 策略名称                   | 说明                                                       |
// * +------+----------------------------+------------------------------------------------------------+
// * | 01   | Cache Aside Pattern        | 缓存的调用者，在更新数据库的同时更新缓存。                 |
// * |      | 旁路缓存模式               |                                                            |
// * +------+----------------------------+------------------------------------------------------------+
// * | 02   | Read/Write Through Pattern | 缓存与数据库整合为一个服务，                              |
// * |      | 读写穿透模式               | 由该服务来维护缓存和数据库的一致性。                      |
// * |      |                            | 调用者只需要调用该服务，                                  |
// * |      |                            | 不需要自己关心缓存一致性问题。                            |
// * +------+----------------------------+------------------------------------------------------------+
// * | 03   | Write Behind Caching       | 调用者只操作缓存，                                        |
// * |      | Pattern                    | 由其他线程异步地将缓存数据持久化到数据库，                |
// * |      | 异步缓存写入模式           | 保证最终一致。                                            |
// * +------+----------------------------+------------------------------------------------------------+
// *
// 一般采用第一种方式，后两种方式实现起来有苦难
// 第一种方式具体方案：采用删除缓存来避免无效读写，并且是先更新数据库，再删除缓存（可以最大程度降低
// 线程安全的风险）